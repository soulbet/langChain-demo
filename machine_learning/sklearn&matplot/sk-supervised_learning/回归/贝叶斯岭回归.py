
from sklearn import linear_model

"""
y=α * x + b
系数不在是固定的数，而是随机变量，求它的概率分布
1、p(α)，先给一个初始分布
2、p(y|x，α) 得到观测数据的概率
3、求后验概率  p(α|y,x)=(p(y|x,α) * p(α)) / p(y)

场景:
1、小样本场景数据少，普通 OLS / 线性回归容易过拟合；贝叶斯靠先验补信息，小样本也能稳建模。
2、高维回归 p≫n特征数远大于样本数，OLS 无解；贝叶斯通过先验正则（高斯→岭回归、拉普拉斯→Lasso）天然实现稀疏与降维。
3、需要预测不确定性不仅要输出预测值，还要给置信区间、概率分布；工业故障、金融风控、医疗预测特别需要。
4、数据倾斜 / 有离群点可以换厚尾先验（t 分布）、偏态似然，抗极端值、矫正分布倾斜，不用人工采样。
5、增量学习 / 在线更新新来数据不用重训全量模型；把上一轮后验当新一轮先验，迭代更新即可。
6、多重共线性严重特征高度相关时，OLS 系数乱跳不稳定；贝叶斯先验约束，解更平滑稳定。


优点：
自带正则化，天然防过拟合，不需要额外加 L1/L2。
输出参数后验分布 + 预测概率区间，不是只给一个定点估计。
小样本、高维、共线性、数据倾斜都能适配。
支持增量学习，适合流式数据更新。
可灵活定制先验，引入领域专家经验。
缺点：
无解析解居多，通常要 MCMC 采样，计算慢，大样本工业场景不友好。
先验选择主观，先验设得不好会严重带偏结果。
理论门槛高，推导、采样调参比普通回归复杂很多。
高维超大特征时，MCMC 收敛慢，不如 LARS、OMP、Lasso 高效。
可解释性比普通线性回归弱，参数是分布不是确定值。
"""

clf = linear_model.BayesianRidge()
clf.fit([[0,0], [1, 1], [2, 2]], [0, 1, 2])

clf.predict([[1, 1]])